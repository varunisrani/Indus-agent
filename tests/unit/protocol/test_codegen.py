@pytest.mark.parametrize(
    ("schema", "expected"),
    [
        ({"type": "string"}, "string"),
        ({"type": "integer", "minimum": 0}, "number"),
        ({"type": "boolean", "default": False}, "boolean"),
        ({"const": "turn.done", "type": "string"}, '"turn.done"'),
        ({"enum": ["a", "b"], "type": "string"}, '"a" | "b"'),
        ({"$ref": "#/$defs/ExitReason"}, "ExitReason"),
        ({"anyOf": [{"type": "string"}, {"type": "null"}]}, "string | null"),
        ({"type": "array", "items": {"type": "string"}}, "string[]"),
        (
            {"type": "array", "items": {"anyOf": [{"type": "string"}, {"type": "integer"}]}},
            "(string | number)[]",
        ),
        (
            {"type": "object", "additionalProperties": {"type": "integer"}},
            "{ [key: string]: number }",
        ),
        ({"type": "object"}, "{ [key: string]: JsonValue }"),
        ({}, "JsonValue"),
        ({"description": "anything"}, "JsonValue"),
    ],
)
def test_ts_type(schema: dict[str, Any], expected: str) -> None:
    assert ts_type(schema) == expected


def test_ts_object_marks_optional_and_const_fields() -> None:
    schema = {
        "type": "object",
        "properties": {
            "kind": {"const": "x", "default": "x"},
            "name": {"type": "string", "description": "The */ name."},
            "note": {"anyOf": [{"type": "string"}, {"type": "null"}], "default": None},
            "odd-key": {"type": "boolean"},
        },
        "required": ["name", "odd-key"],
    }
    text = ts_type(schema)
    assert '  kind: "x";' in text
    assert "  name: string;" in text
    assert "  note?: string | null;" in text
    assert '  "odd-key": boolean;' in text
    assert "/** The *\\/ name. */" in text


