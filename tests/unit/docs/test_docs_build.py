"""P25-14: the docs site builds in strict mode, and its llms files list every page."""

from __future__ import annotations

import os
import shutil
from collections.abc import Iterator
from pathlib import Path
from typing import Any

import pytest
import yaml
from mkdocs.commands.build import build
from mkdocs.config import load_config
from mkdocs.exceptions import Abort, PluginError

from scripts.docs import llms_txt

ROOT = Path(__file__).resolve().parents[3]
CONFIG = ROOT / "mkdocs.yml"
DOCS = ROOT / "docs" / "user"


def _build(site_dir: Path, **overrides: Any) -> None:
    cwd = Path.cwd()
    os.chdir(ROOT)  # hooks: and docs_dir in mkdocs.yml are relative to the repository
    try:
        config = load_config(config_file=str(CONFIG), site_dir=str(site_dir), **overrides)
        try:
            build(config)
        finally:
            config.plugins.on_shutdown()
    finally:
        os.chdir(cwd)


@pytest.fixture(scope="module")
def site(tmp_path_factory: pytest.TempPathFactory) -> Iterator[Path]:
    out = tmp_path_factory.mktemp("docs-site")
    _build(out)
    yield out
    shutil.rmtree(out, ignore_errors=True)


def _nav() -> list[llms_txt.NavPage]:
    # mkdocs.yml has no custom YAML tags, so the plain loader reads it.
    data = yaml.safe_load(CONFIG.read_text(encoding="utf-8"))
    return llms_txt.nav_pages(data["nav"])


def test_strict_build_of_the_real_tree(site: Path) -> None:
    config = yaml.safe_load(CONFIG.read_text(encoding="utf-8"))
    assert config["strict"] is True
    assert (site / "index.html").is_file()
    assert (site / "search" / "search_index.json").is_file()
    for page in _nav():
        target = site / llms_txt.page_url(page.path).lstrip("/") / "index.html"
        assert target.is_file(), page.path


def test_every_markdown_page_is_in_the_navigation() -> None:
    assert llms_txt.missing_from_nav(DOCS, _nav()) == []


def test_llms_index_lists_every_page(site: Path) -> None:
    index = (site / llms_txt.INDEX_FILE).read_text(encoding="utf-8")
    assert index.startswith("# Indus Agent\n")
    for page in _nav():
        assert f"]({llms_txt.page_url(page.path)})" in index, page.path
    for section in ("## Getting started", "## User guide", "## Messaging", "## Reference"):
        assert section in index


def test_llms_full_holds_every_page_in_order(site: Path) -> None:
    full = (site / llms_txt.FULL_FILE).read_text(encoding="utf-8")
    positions = [full.index(f"<!-- page: {page.path} |") for page in _nav()]
    assert positions == sorted(positions)
    assert "<!-- test" not in full
    assert "Generated by scripts/docs/gen_reference.py" not in full


def _scratch_tree(base: Path, extra: str) -> Path:
    docs = base / "docs"
    docs.mkdir(parents=True)
    (docs / "index.md").write_text("# Home\n\nWelcome. See [the guide](guide.md).\n", "utf-8")
    (docs / "guide.md").write_text(f"# Guide\n\nThe guide.\n\n## Part\n\n{extra}\n", "utf-8")
    return docs


@pytest.mark.parametrize(
    "link",
    ["[gone](missing.md)", "[bad anchor](index.md#no-such-heading)"],
    ids=["missing-page", "missing-anchor"],
)
def test_a_broken_link_fails_the_build(tmp_path: Path, link: str) -> None:
    docs = _scratch_tree(tmp_path, link)
    with pytest.raises(Abort):
        _build(
            tmp_path / "site",
            docs_dir=str(docs),
            nav=[{"Home": "index.md"}, {"Guide": "guide.md"}],
        )


def test_a_page_left_out_of_the_navigation_fails_the_build(tmp_path: Path) -> None:
    docs = _scratch_tree(tmp_path, "Fine.")
    with pytest.raises((Abort, PluginError)):
        _build(tmp_path / "site", docs_dir=str(docs), nav=[{"Home": "index.md"}])


def test_a_clean_scratch_tree_builds(tmp_path: Path) -> None:
    docs = _scratch_tree(tmp_path, "See [the top](index.md#home).")
    site = tmp_path / "site"
    _build(site, docs_dir=str(docs), nav=[{"Home": "index.md"}, {"Guide": "guide.md"}])
    index = (site / "llms.txt").read_text(encoding="utf-8")
    assert "- [Home](/): Welcome." in index
    assert "- [Guide](/guide/): The guide." in index


