def test_nav_pages_keeps_order_and_top_sections() -> None:
    nav = [
        {"Home": "index.md"},
        {"Start": [{"Install": "start/install.md"}, {"Deep": [{"More": "start/more.md"}]}]},
        {"Repo": "https://example.com"},
    ]
    assert llms_txt.nav_pages(nav) == [
        llms_txt.NavPage("Overview", "Home", "index.md"),
        llms_txt.NavPage("Start", "Install", "start/install.md"),
        llms_txt.NavPage("Start", "More", "start/more.md"),
    ]


@pytest.mark.parametrize(
    ("path", "site_url", "directory", "url"),
    [
        ("index.md", "", True, "/"),
        ("guide/index.md", "", True, "/guide/"),
        ("guide/cli.md", "", True, "/guide/cli/"),
        ("guide/cli.md", "https://docs.example.org/", True, "https://docs.example.org/guide/cli/"),
        ("guide/cli.md", "", False, "/guide/cli.html"),
    ],
)
def test_page_url(path: str, site_url: str, directory: bool, url: str) -> None:
    assert llms_txt.page_url(path, site_url, directory) == url


def test_summary_skips_markers_tables_and_code() -> None:
    text = (
        "<!-- Generated -->\n\n# Title\n\n| a | b |\n|---|---|\n\n```bash\nx\n```\n\n"
        "The first [real](x.md) sentence. The second.\n"
    )
    assert llms_txt.title_of(text, "fallback") == "Title"
    assert llms_txt.summary_of(text) == "The first real sentence."


def test_docs_workflow_builds_strict_and_deploys_on_main_and_releases() -> None:
    workflow = yaml.safe_load((ROOT / ".github" / "workflows" / "docs.yml").read_text("utf-8"))
    triggers = workflow[True]  # YAML 1.1 reads the key `on` as true
    assert triggers["push"]["branches"] == ["main"]
    assert "docs/user/**" in triggers["push"]["paths"]
    assert triggers["release"]["types"] == ["published"]
    steps = " ".join(str(step.get("run", "")) for step in workflow["jobs"]["build"]["steps"])
    assert "gen_reference.py --check" in steps
    assert "mkdocs build --strict" in steps
    deploy = workflow["jobs"]["deploy"]
    assert deploy["needs"] == "build"
    assert deploy["permissions"] == {"pages": "write", "id-token": "write"}
