"""The REST route list the SPA's tests import is generated from the route modules (P18-11..16).

Every route module under ``indus.web.routes`` that serves REST data declares ``ROUTE_LIST``
(``(method, path, scoped)``), pinned against the mounted app by its own contract test. Here the
union of those lists is (1) checked against every ``/api`` route the real app mounts, so a route
cannot be added without listing it, and (2) rendered into ``apps/web/src/test/routes.generated.ts``,
which ``api.test.ts`` reads to pin ``PROFILE_SCOPED_FAMILIES`` to the backend. When a route
changes, regenerate the file with::

    INDUS_WRITE_ROUTE_LIST=1 uv run pytest tests/contract/web/test_route_list.py
"""

from __future__ import annotations

import importlib
import os
from collections.abc import Iterator
from pathlib import Path

import pytest

from indus.foundation.scope import Scope
from indus.web.routes import ROUTERS
from indus.web.scope import unscoped_write_routes
from tests.contract.web.rest_app import RestApp, build_rest_app, route_table

ROOT = Path(__file__).resolve().parents[3]
GENERATED = ROOT / "apps" / "web" / "src" / "test" / "routes.generated.ts"
WRITE_ENV = "INDUS_WRITE_ROUTE_LIST"
WRITE = os.environ.get(WRITE_ENV) == "1"
"""Read at import: the suite's autouse fixture drops every ``INDUS_*`` variable before a test."""
CATCH_ALL = frozenset({"/api", "/api/{rest:path}"})
"""The SPA mount's JSON 404 for unknown ``/api`` paths (``web.spa``), not a route."""

NOT_LISTED = frozenset(
    {
        ("GET", "/api/health", False),
        ("GET", "/api/auth/me", False),
        ("GET", "/api/auth/providers", False),
        ("POST", "/api/auth/ws-ticket", False),
    }
)
"""Mounted ``/api`` routes outside the REST families: liveness and the auth round trip (P18-02..06),
which the SPA reaches through its bootstrap, not the route list."""

HEADER = """\
// GENERATED by tests/contract/web/test_route_list.py from the ROUTE_LIST constants of
// src/indus/web/routes/*.py; do not edit. Regenerate:
//   INDUS_WRITE_ROUTE_LIST=1 uv run pytest tests/contract/web/test_route_list.py
// One entry per REST route: method, path template (`{name}` placeholders) and whether the route
// resolves a profile scope (takes `?profile=`, R09.20).

export interface GeneratedRoute {
  method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";
  path: string;
  scoped: boolean;
}

export const GENERATED_ROUTES: readonly GeneratedRoute[] = [
"""


def listed_routes() -> list[tuple[str, str, bool]]:
    rows: set[tuple[str, str, bool]] = set()
    for spec in ROUTERS:
        module = importlib.import_module(spec.partition(":")[0])
        rows.update(getattr(module, "ROUTE_LIST", ()))
    return sorted(rows, key=lambda row: (row[1], row[0]))


def render() -> str:
    lines = [
        f'  {{ method: "{method}", path: "{path}", scoped: {str(scoped).lower()} }},'
        for method, path, scoped in listed_routes()
    ]
    return HEADER + "\n".join(lines) + "\n];\n"


@pytest.fixture
def rest(scope: Scope) -> Iterator[RestApp]:
    built = build_rest_app(scope)
    yield built
    built.close()


def test_every_mounted_rest_route_is_listed(rest: RestApp) -> None:
    mounted = {row for row in route_table(rest.app, ("/api",)) if row[1] not in CATCH_ALL}
    assert mounted - NOT_LISTED == set(listed_routes())
    assert mounted >= NOT_LISTED


UNSCOPED_WRITES = frozenset(
    {
        # the auth round trip and the WebSocket ticket (P18-03, P18-06): no profile data
        "POST /auth/password-login",
        "POST /auth/logout",
        "POST /api/auth/ws-ticket",
        # its own signed token names the profile (P18-14)
        "POST /api/cron/fire",
        # the service-bearer drain: the backend's own profile unless ?profile= (P18-15)
        "POST /api/daemon/drain",
        # profile management names the profile in the path or body (P18-16)
        "POST /api/profiles",
        "POST /api/profiles/active",
        "POST /api/profiles/import",
        "PATCH /api/profiles/{name}",
        "DELETE /api/profiles/{name}",
        "PUT /api/profiles/{name}/persona",
        "PUT /api/profiles/{name}/description",
        "PUT /api/profiles/{name}/model",
        "POST /api/profiles/{name}/export",
        # the host's files are machine-level (P18-16)
        "POST /api/files/download-ticket",
        "POST /api/files/mkdir",
        "POST /api/files/upload",
        "DELETE /api/files",
        # the dashboard plugin catalogue is the backend's own (P24-37)
        "POST /api/dashboard/plugins/rescan",
    }
)
"""Every write route of the real app that deliberately takes no profile (R09.20)."""


def test_every_other_write_route_needs_a_profile(rest: RestApp) -> None:
    found = {
        row
        for row in unscoped_write_routes(rest.app)
        if row.partition(" ")[2] not in CATCH_ALL | {"/{rest:path}"}
    }
    assert found == UNSCOPED_WRITES


def test_no_route_is_listed_twice() -> None:
    seen: dict[tuple[str, str], bool] = {}
    for method, path, scoped in listed_routes():
        assert (method, path) not in seen, f"{method} {path} is listed with two scoped flags"
        seen[(method, path)] = scoped


def test_the_spa_route_list_is_generated() -> None:
    expected = render()
    if WRITE:
        GENERATED.write_text(expected, encoding="utf-8")
    assert GENERATED.read_text(encoding="utf-8") == expected, (
        f"{GENERATED.relative_to(ROOT)} is stale; regenerate it with {WRITE_ENV}=1"
    )
