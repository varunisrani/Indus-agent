"""Write or check ``field_docs.json``: the field docstrings of every wire-model module (W48-g-2).

Wire-model field docstrings are the field descriptions of the JSON Schema (``codegen``). Pydantic's
``use_attribute_docstrings`` found them by re-parsing each class's source at import, ~55 ms of every
start; ``ProtocolModel`` now reads them from this generated twin, which records each module's
sha256. A module whose source no longer matches its digest (or is not in the twin) is parsed once
instead, so a stale twin costs time, never a wrong description.

Usage: ``uv run python -m indus.protocol.field_docs`` rewrites the twin; ``--check`` exits 1 when it
is stale (a unit test runs the same check).
"""

from __future__ import annotations

import argparse
import ast
import json
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from indus.protocol.base import DOCS_TWIN, class_docs, source_digest

SRC = Path(__file__).resolve().parents[2]
MARKER = "ProtocolModel"
NOTE = "generated by `python -m indus.protocol.field_docs`; do not edit"


def modules(src: Path = SRC) -> list[Path]:
    """The modules under ``src/indus`` that may define wire models, sorted."""
    found: list[Path] = []
    for path in sorted((src / "indus").rglob("*.py")):
        if "__pycache__" in path.parts:
            continue
        if path.parent.name == "protocol" or MARKER in path.read_text(encoding="utf-8"):
            found.append(path)
    return found


def render(src: Path = SRC) -> str:
    """The twin's text for the tree under ``src``."""
    table: dict[str, Any] = {}
    for path in modules(src):
        data = path.read_bytes()
        parts = path.relative_to(src).with_suffix("").parts
        name = ".".join(parts[:-1] if parts[-1] == "__init__" else parts)
        classes = {str(line): docs for line, docs in sorted(class_docs(ast.parse(data)).items())}
        table[name] = {"sha256": source_digest(data), "classes": classes}
    twin = {"note": NOTE, "modules": table}
    return json.dumps(twin, indent=1, ensure_ascii=False, sort_keys=True) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m indus.protocol.field_docs", description=(__doc__ or "").splitlines()[0]
    )
    parser.add_argument("--check", action="store_true", help="exit 1 if the twin is stale")
    args = parser.parse_args(argv)
    wanted = render()
    current = DOCS_TWIN.read_text(encoding="utf-8") if DOCS_TWIN.is_file() else None
    if args.check:
        if current == wanted:
            return 0
        sys.stdout.write(
            f"{DOCS_TWIN.name} is stale; run `uv run python -m indus.protocol.field_docs`\n"
        )
        return 1
    if current != wanted:
        DOCS_TWIN.write_text(wanted, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
