"""Generate the TypeScript protocol package from the Python models (D-04.3).

``python -m indus.protocol.codegen`` writes ``schema.json``, ``types.ts`` and ``catalog.ts`` into
``packages/protocol/src/generated/``. ``--check`` builds the same files in memory and exits 1 with
a unified diff when anything on disk differs, so stale output fails CI. Output is deterministic:
sorted keys, LF line ends and one trailing newline.

The TypeScript is produced by a small translator over the JSON Schema subset pydantic emits for
our models; a shape outside that subset is a ``CodegenError``, never a silent ``any``.
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
from collections.abc import Iterable, Mapping, Sequence
from pathlib import Path
from typing import Any, cast

from pydantic import TypeAdapter

from indus.protocol.envelope import (
    ErrorDetail,
    ErrorObject,
    ErrorResponse,
    Notification,
    Request,
    SuccessResponse,
)
from indus.protocol.errors import ERROR_TABLE, GROUP_STATUS
from indus.protocol.events import EVENTS, Event, TurnFailure
from indus.protocol.methods import METHODS, PROTOCOL_VERSION
from indus.protocol.server_requests import (
    SERVER_REQUEST_KINDS,
    SERVER_REQUEST_METHOD,
    ClarifyQuestion,
    ServerRequest,
    ServerRequestAnswer,
)

REPO_ROOT = Path(__file__).resolve().parents[3]
GENERATED_DIR = Path("packages/protocol/src/generated")
COMMAND = "python -m indus.protocol.codegen"
NOTICE = f"Generated by `{COMMAND}`. Do not edit: change the Python models and regenerate."
TS_HEADER = f"// {NOTICE}\n\n"
DESCRIPTION = "Generate the TypeScript protocol package from the Python models."
SCHEMA_DIALECT = "https://json-schema.org/draft/2020-12/schema"

_IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")
# Keywords that only constrain values; TypeScript cannot express them, so they are skipped.
_IGNORED = frozenset(
    {
        "title",
        "description",
        "default",
        "format",
        "minLength",
        "maxLength",
        "minimum",
        "maximum",
        "exclusiveMinimum",
        "exclusiveMaximum",
        "minItems",
        "maxItems",
        "pattern",
        "uniqueItems",
        "discriminator",
        "additionalProperties",
        "properties",
        "required",
        "items",
        "type",
    }
)
_JSON_VALUE_TS = "string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue }"

type Json = Any


class CodegenError(Exception):
    """The models produced a schema shape the generator does not translate."""


# --- collecting the schema ---------------------------------------------------------------------


def _named_roots() -> list[tuple[str, TypeAdapter[Any]]]:
    roots: dict[str, object] = {}
    for model in (
        Request,
        Notification,
        SuccessResponse,
        ErrorResponse,
        ErrorObject,
        ErrorDetail,
        TurnFailure,
        ClarifyQuestion,
    ):
        roots[model.__name__] = model
    for spec in METHODS.values():
        roots[spec.params.__name__] = spec.params
        roots[spec.result.__name__] = spec.result
    for model in EVENTS.values():
        roots[model.__name__] = model
    for request, answer in SERVER_REQUEST_KINDS.values():
        roots[request.__name__] = request
        roots[answer.__name__] = answer
    roots["Event"] = Event
    roots["ServerRequest"] = ServerRequest
    roots["ServerRequestAnswer"] = ServerRequestAnswer
    return [(name, TypeAdapter(obj)) for name, obj in sorted(roots.items())]


def _strip_titles(node: Json, *, in_properties: bool = False) -> Json:
    """Drop pydantic's auto ``title`` keywords (property names called ``title`` are kept)."""
    if isinstance(node, dict):
        out: dict[str, Json] = {}
        for key, value in cast(dict[str, Json], node).items():
            if key == "title" and not in_properties:
                continue
            out[key] = _strip_titles(value, in_properties=key == "properties" and not in_properties)
        return out
    if isinstance(node, list):
        return [_strip_titles(v) for v in cast(list[Json], node)]
    return node


def _catalog_data() -> dict[str, Json]:
    return {
        "version": PROTOCOL_VERSION,
        "methods": {
            spec.name: {
                "params": spec.params.__name__,
                "result": spec.result.__name__,
                "errors": [e.name for e in spec.errors],
            }
            for spec in METHODS.values()
        },
        "events": {name: model.__name__ for name, model in EVENTS.items()},
        "server_request_method": SERVER_REQUEST_METHOD,
        "server_requests": {
            kind: {"request": req.__name__, "answer": ans.__name__}
            for kind, (req, ans) in SERVER_REQUEST_KINDS.items()
        },
        "error_groups": {group.value: status for group, status in GROUP_STATUS.items()},
        "errors": {
            e.name: {
                "code": e.code,
                "group": e.group.value,
                "status": e.status,
                "meaning": e.meaning,
            }
            for e in ERROR_TABLE
        },
    }


def build_schema() -> dict[str, Json]:
    """The whole protocol as one JSON Schema document."""
    roots = _named_roots()
    key_map, top = TypeAdapter.json_schemas(
        [(name, "validation", adapter) for name, adapter in roots],
        ref_template="#/$defs/{model}",
    )
    defs: dict[str, Json] = dict(top.get("$defs", {}))
    for (name, _mode), schema in key_map.items():
        ref = schema.get("$ref")
        if ref != f"#/$defs/{name}":
            if ref is not None and len(schema) == 1:
                raise CodegenError(f"{name} was registered as {ref}; class names must be unique")
            defs[name] = schema
    for name in defs:
        if not _IDENT.match(name):
            raise CodegenError(f"schema def name {name!r} is not a plain identifier")
    return {
        "$comment": NOTICE,
        "$schema": SCHEMA_DIALECT,
        "$defs": _strip_titles(defs),
        "title": "Indus Agent protocol",
        "x-indus-catalog": _catalog_data(),
    }


# --- JSON Schema → TypeScript ------------------------------------------------------------------


def _literal(value: Json) -> str:
    return json.dumps(value, ensure_ascii=False)


def _union(parts: Iterable[str]) -> str:
    seen: list[str] = []
    for part in parts:
        if part not in seen:
            seen.append(part)
    return " | ".join(seen)


def _wrap(ts: str) -> str:
    return f"({ts})" if " | " in ts else ts


def _check_keys(schema: Mapping[str, Json], allowed: Iterable[str]) -> None:
    extra = set(schema) - _IGNORED - set(allowed)
    if extra:
        raise CodegenError(f"unsupported schema keywords {sorted(extra)} in {schema!r}")


def ts_type(schema: Mapping[str, Json], indent: str = "") -> str:
    """Translate one schema node into a TypeScript type expression."""
    if "$ref" in schema:
        _check_keys(schema, ["$ref"])
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "const" in schema:
        _check_keys(schema, ["const"])
        return _literal(schema["const"])
    if "enum" in schema:
        _check_keys(schema, ["enum"])
        return _union(_literal(v) for v in cast(list[Json], schema["enum"]))
    for key in ("anyOf", "oneOf"):
        if key in schema:
            _check_keys(schema, [key])
            members = cast(list[Mapping[str, Json]], schema[key])
            return _union(ts_type(m, indent) for m in members)
    kind = schema.get("type")
    _check_keys(schema, [])
    if kind is None:
        if set(schema) - _IGNORED:
            raise CodegenError(f"untyped schema {schema!r}")
        return "JsonValue"
    if not isinstance(kind, str):
        raise CodegenError(f"type lists are not supported: {schema!r}")
    simple = {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }
    if kind in simple:
        return simple[kind]
    if kind == "array":
        items = cast(Mapping[str, Json] | None, schema.get("items"))
        return f"{_wrap(ts_type(items, indent))}[]" if items is not None else "JsonValue[]"
    if kind == "object":
        if "properties" in schema:
            return _object_body(schema, indent)
        extra = schema.get("additionalProperties")
        value = (
            ts_type(cast(Mapping[str, Json], extra), indent)
            if isinstance(extra, dict)
            else ("JsonValue")
        )
        return f"{{ [key: string]: {value} }}"
    raise CodegenError(f"unsupported type {kind!r}")


def _doc(text: str | None, indent: str) -> list[str]:
    if not text:
        return []
    lines = text.replace("``", "`").replace("*/", "*\\/").strip().splitlines()
    if len(lines) == 1:
        return [f"{indent}/** {lines[0]} */"]
    return [f"{indent}/**", *(f"{indent} * {line}".rstrip() for line in lines), f"{indent} */"]


def _object_body(schema: Mapping[str, Json], indent: str) -> str:
    properties = cast(dict[str, Mapping[str, Json]], schema["properties"])
    required = set(cast(list[str], schema.get("required", [])))
    inner = indent + "  "
    lines = ["{"]
    for name, prop in properties.items():
        key = name if _IDENT.match(name) else _literal(name)
        optional = name not in required and "const" not in prop
        lines.extend(_doc(cast(str | None, prop.get("description")), inner))
        lines.append(f"{inner}{key}{'?' if optional else ''}: {ts_type(prop, inner)};")
    lines.append(f"{indent}}}")
    return "\n".join(lines)


def render_types(schema: Mapping[str, Json]) -> str:
    """``types.ts``: one exported type per schema def."""
    defs = cast(dict[str, Mapping[str, Json]], schema["$defs"])
    blocks: list[str] = []
    for name in sorted(defs):
        node = defs[name]
        doc = _doc(cast(str | None, node.get("description")), "")
        if name == "JsonValue" and not (set(node) - _IGNORED):
            body = f"export type JsonValue = {_JSON_VALUE_TS};"
            doc = doc or ["/** Any JSON value. */"]
        elif node.get("type") == "object" and "properties" in node:
            body = f"export interface {name} {_object_body(node, '')}"
        else:
            body = f"export type {name} = {ts_type(node)};"
        blocks.append("\n".join([*doc, body]))
    return TS_HEADER + "\n\n".join(blocks) + "\n"


def _const(value: Json) -> str:
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False)


def _type_map(name: str, rows: Mapping[str, Mapping[str, str] | str]) -> str:
    lines = [f"export interface {name} {{"]
    for key in sorted(rows):
        row = rows[key]
        if isinstance(row, str):
            value = f"T.{row}"
        else:
            value = "{ " + "; ".join(f"{k}: T.{v}" for k, v in sorted(row.items())) + " }"
        lines.append(f"  {_literal(key)}: {value};")
    lines.append("}")
    return "\n".join(lines)


def render_catalog(schema: Mapping[str, Json]) -> str:
    """``catalog.ts``: the catalogue and the frozen error table as constants."""
    data = cast(dict[str, Json], schema["x-indus-catalog"])
    methods = cast(dict[str, dict[str, Json]], data["methods"])
    events = cast(dict[str, str], data["events"])
    kinds = cast(dict[str, dict[str, str]], data["server_requests"])
    parts = [
        'import type * as T from "./types.ts";',
        "function deepFreeze<V>(value: V): V {\n"
        '  if (typeof value === "object" && value !== null) {\n'
        "    for (const inner of Object.values(value)) deepFreeze(inner);\n"
        "    Object.freeze(value);\n"
        "  }\n"
        "  return value;\n"
        "}",
        "/** Bumped when a change breaks existing clients. */\n"
        f"export const PROTOCOL_VERSION = {data['version']};",
        "/** Method name → params type, result type and the error names it may return. */\n"
        f"export const METHODS = deepFreeze({_const(methods)} as const);",
        "export type MethodName = keyof typeof METHODS;",
        _type_map(
            "MethodTypes",
            {
                m: {"params": str(v["params"]), "result": str(v["result"])}
                for m, v in methods.items()
            },
        ),
        "/** Event type (also the notification method) → event type name. */\n"
        f"export const EVENTS = deepFreeze({_const(events)} as const);",
        "export type EventName = keyof typeof EVENTS;",
        _type_map("EventTypes", events),
        "/** The notification method that carries a server request. */\n"
        f"export const SERVER_REQUEST_METHOD = {_literal(data['server_request_method'])};",
        "/** Server-request kind → request and answer type names. */\n"
        f"export const SERVER_REQUEST_KINDS = deepFreeze({_const(kinds)} as const);",
        "export type ServerRequestKind = keyof typeof SERVER_REQUEST_KINDS;",
        _type_map("ServerRequestTypes", cast(Mapping[str, Mapping[str, str]], kinds)),
        "/** Error group → HTTP-like status. */\n"
        f"export const ERROR_GROUPS = deepFreeze({_const(data['error_groups'])} as const);",
        "/** The single error-code table: one meaning per code. */\n"
        f"export const ERROR_CODES = deepFreeze({_const(data['errors'])} as const);",
        "export type ErrorName = keyof typeof ERROR_CODES;",
    ]
    return TS_HEADER + "\n\n".join(parts) + "\n"


def dump_json(value: Json, indent: int = 0, used: int = 0, width: int = 100) -> str:
    """Sorted-key JSON; a container that fits on the current line stays on one line.

    ``indent`` is the nesting indent, ``used`` the columns already taken on the current line.
    """
    flat = json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(", ", ": "))
    if not isinstance(value, dict | list) or not value or used + len(flat) <= width:
        return flat
    pad = " " * (indent + 2)
    if isinstance(value, list):
        items = [pad + dump_json(v, indent + 2, len(pad), width) for v in cast(list[Json], value)]
        return "[\n" + ",\n".join(items) + "\n" + " " * indent + "]"
    rows: list[str] = []
    for key in sorted(cast(dict[str, Json], value)):
        head = f"{pad}{json.dumps(key, ensure_ascii=False)}: "
        rows.append(head + dump_json(value[key], indent + 2, len(head), width))
    return "{\n" + ",\n".join(rows) + "\n" + " " * indent + "}"


def render_all() -> dict[str, str]:
    """Generated file name → text."""
    schema = build_schema()
    return {
        "schema.json": dump_json(schema) + "\n",
        "types.ts": render_types(schema),
        "catalog.ts": render_catalog(schema),
    }


# --- writing and checking ----------------------------------------------------------------------


def write(out_dir: Path, files: Mapping[str, str]) -> None:
    """Write ``files`` into ``out_dir`` with LF line ends."""
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, text in sorted(files.items()):
        (out_dir / name).write_text(text, encoding="utf-8", newline="\n")


def stale_report(out_dir: Path, files: Mapping[str, str], label: str) -> list[str]:
    """Unified diffs (disk → fresh) for every file that differs; empty when up to date."""
    report: list[str] = []
    for name, fresh in sorted(files.items()):
        path = out_dir / name
        try:
            current = path.read_bytes().decode("utf-8")
        except FileNotFoundError:
            report.append(f"missing: {label}/{name}\n")
            continue
        if current != fresh:
            diff = difflib.unified_diff(
                current.splitlines(keepends=True),
                fresh.splitlines(keepends=True),
                fromfile=f"{label}/{name} (on disk)",
                tofile=f"{label}/{name} (generated)",
            )
            report.append("".join(diff) or f"differs (line ends or encoding): {label}/{name}\n")
    if out_dir.is_dir():
        names = (p.name for p in out_dir.iterdir() if not p.name.startswith("."))
        for extra in sorted(n for n in names if n not in files):
            report.append(f"unexpected file: {label}/{extra}\n")
    return report


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog=COMMAND, description=DESCRIPTION)
    parser.add_argument("--check", action="store_true", help="exit 1 with a diff when stale")
    parser.add_argument("--root", type=Path, default=REPO_ROOT, help="repository root")
    args = parser.parse_args(argv)
    out_dir = cast(Path, args.root) / GENERATED_DIR
    files = render_all()
    if args.check:
        report = stale_report(out_dir, files, GENERATED_DIR.as_posix())
        if report:
            sys.stdout.write("".join(report))
            sys.stdout.write(f"protocol output is stale; run `{COMMAND}`\n")
            return 1
        return 0
    write(out_dir, files)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
