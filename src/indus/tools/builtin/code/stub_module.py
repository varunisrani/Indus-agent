# pyright: strict
"""The source of ``indus_tools``, the module a script imports to call our tools (P10-09).

``module_source(tools, transport)`` writes one function per allowed tool the session has, the
three helpers (``json_parse``, ``shell_quote``, ``retry``) and one of two transports:

- ``socket``: newline-delimited JSON over the Unix socket (or ``tcp://127.0.0.1:<port>``) named
  by ``INDUS_RPC_SOCKET``; one lock serialises round trips so script threads never read each
  other's answers; a kernel's stub (``INDUS_RPC_PERSISTENT=1``) reconnects once after a drop.
- ``file``: for remote backends. A request is written owner-only to a temp name in
  ``INDUS_RPC_DIR`` and renamed to ``req_<seq>.json``; the answer appears as
  ``res_<seq>.json``; the wait grows from 50 ms to 250 ms and gives up after
  ``RPC_CALL_WAIT_S``.

Every request carries ``INDUS_RPC_TOKEN``. An answer is ``{"result": <text>}`` (the tool's own
result: parsed when it is JSON, else returned as text) or ``{"refused": <why>}``, which raises
``ToolCallRefused`` in the script. The module uses the standard library only, so it works under
any Python 3.8+ the project's virtualenv provides.
"""

from __future__ import annotations

from collections.abc import Iterable
from dataclasses import dataclass
from typing import Literal

from indus.tools.builtin.code.settings import MODULE_NAME, RPC_CALL_WAIT_S

type Transport = Literal["socket", "file"]

ENV_SOCKET = "INDUS_RPC_SOCKET"
ENV_TOKEN = "INDUS_RPC_TOKEN"
ENV_DIR = "INDUS_RPC_DIR"
ENV_PERSISTENT = "INDUS_RPC_PERSISTENT"

HELPERS: tuple[str, ...] = ("json_parse", "shell_quote", "retry")


@dataclass(frozen=True)
class Stub:
    signature: str
    doc: str
    payload: str  # a Python dict expression over the parameters


# One entry per tool a script may call, in the order the description lists them.
STUBS: dict[str, Stub] = {
    "read_file": Stub(
        "path, offset=1, limit=None",
        "Lines of a text file, numbered from 1. Returns a dict with the file's content.",
        '{"path": path, "offset": offset, "limit": limit}',
    ),
    "write_file": Stub(
        "path, content",
        "Replace a file's whole content (an existing file must have been read first).",
        '{"path": path, "content": content}',
    ),
    "patch": Stub(
        "path, old_string, new_string, replace_all=False",
        "Swap one exact piece of a file for another.",
        '{"path": path, "old_string": old_string, "new_string": new_string, '
        '"replace_all": replace_all}',
    ),
    "search_files": Stub(
        'pattern, target="content", path=".", file_glob=None, limit=50, offset=0, '
        'output_mode="content", context=0',
        'Search inside files (target="content") or for file names (target="files").',
        '{"pattern": pattern, "target": target, "path": path, "file_glob": file_glob, '
        '"limit": limit, "offset": offset, "output_mode": output_mode, "context": context}',
    ),
    "web_search": Stub(
        "query, limit=5",
        "Ranked web results: title, address and snippet for each.",
        '{"query": query, "limit": limit}',
    ),
    "web_extract": Stub(
        "urls, char_limit=None",
        "The readable text of each page address given.",
        '{"urls": urls, "char_limit": char_limit}',
    ),
    "terminal": Stub(
        "command, timeout=None, workdir=None, **options",
        "Run one shell command in the foreground and wait for it.",
        '{"command": command, "timeout": timeout, "workdir": workdir, **options}',
    ),
}


_PRELUDE = '''\
"""Generated by Indus Agent for one execute_code run: call Indus tools from Python."""
import json
import os
import shlex
import threading
import time

__all__ = [__NAMES__]

_TOKEN = os.environ.get("INDUS_RPC_TOKEN", "")
_WAIT_S = __WAIT__


class ToolCallRefused(RuntimeError):
    """Indus refused the call itself (unknown tool, call budget used up, bad arguments)."""


def json_parse(text):
    """json.loads that also accepts raw control characters inside strings and a leading BOM."""
    if isinstance(text, (bytes, bytearray)):
        text = bytes(text).decode("utf-8", errors="replace")
    if isinstance(text, str) and text[:1] == "\\ufeff":
        text = text[1:]
    return json.loads(text, strict=False)


def shell_quote(value):
    """Quote one value for use inside a shell command line."""
    return shlex.quote(str(value))


def retry(fn, max_attempts=3, delay=2):
    """Call fn() until it does not raise, at most max_attempts times; waits double each time."""
    attempts = max(1, int(max_attempts))
    for attempt in range(attempts):
        try:
            return fn()
        except Exception:
            if attempt + 1 >= attempts:
                raise
            time.sleep(delay * (2 ** attempt))


def _answer(raw):
    try:
        reply = json.loads(raw)
    except ValueError:
        raise ToolCallRefused("Indus sent an answer that is not JSON") from None
    if not isinstance(reply, dict):
        raise ToolCallRefused("Indus sent an answer of the wrong shape")
    if "refused" in reply:
        raise ToolCallRefused(str(reply["refused"]))
    result = reply.get("result")
    if isinstance(result, str):
        try:
            return json.loads(result)
        except ValueError:
            return result
    return result
'''

_SOCKET_TRANSPORT = """
import socket

_lock = threading.Lock()
_conn = None
_PERSISTENT = os.environ.get("INDUS_RPC_PERSISTENT") == "1"


def _open():
    endpoint = os.environ["INDUS_RPC_SOCKET"]
    if endpoint.startswith("tcp://"):
        host, _, port = endpoint[len("tcp://"):].rpartition(":")
        conn = socket.create_connection((host or "127.0.0.1", int(port)))
    else:
        conn = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        conn.connect(endpoint)
    conn.settimeout(_WAIT_S)
    return conn


def _round_trip(line):
    global _conn
    if _conn is None:
        _conn = _open()
    _conn.sendall(line)
    chunks = []
    while True:
        chunk = _conn.recv(1 << 16)
        if not chunk:
            raise ConnectionError("Indus closed the tool connection")
        chunks.append(chunk)
        if chunk.endswith(b"\\n"):
            return b"".join(chunks)


def _call(tool, args):
    global _conn
    args = {key: value for key, value in args.items() if value is not None}
    line = (json.dumps({"tool": tool, "args": args, "token": _TOKEN}) + "\\n").encode("utf-8")
    tries = 2 if _PERSISTENT else 1
    with _lock:
        for attempt in range(tries):
            try:
                raw = _round_trip(line)
                break
            except (OSError, ConnectionError):
                if _conn is not None:
                    try:
                        _conn.close()
                    except OSError:
                        pass
                _conn = None
                if attempt + 1 >= tries:
                    raise
    return _answer(raw.decode("utf-8", errors="replace"))
"""

_FILE_TRANSPORT = """
_lock = threading.Lock()
_seq = 0


def _call(tool, args):
    global _seq
    args = {key: value for key, value in args.items() if value is not None}
    folder = os.environ["INDUS_RPC_DIR"]
    with _lock:
        _seq += 1
        number = "%06d" % _seq
    request = os.path.join(folder, "req_" + number + ".json")
    answer = os.path.join(folder, "res_" + number + ".json")
    partial = request + ".part"
    body = json.dumps({"tool": tool, "args": args, "token": _TOKEN, "seq": _seq})
    fd = os.open(partial, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        handle.write(body)
    os.replace(partial, request)
    deadline = time.monotonic() + _WAIT_S
    gap = 0.05
    while not os.path.exists(answer):
        if time.monotonic() > deadline:
            raise TimeoutError("no answer from Indus for %s within %ss" % (tool, _WAIT_S))
        time.sleep(gap)
        gap = min(gap * 1.25, 0.25)
    with open(answer, encoding="utf-8") as handle:
        raw = handle.read()
    try:
        os.remove(answer)
    except OSError:
        pass
    return _answer(raw)
"""


def _function(name: str, stub: Stub) -> str:
    return (
        f"\n\ndef {name}({stub.signature}):\n"
        f'    """{stub.doc}"""\n'
        f"    return _call({name!r}, {stub.payload})\n"
    )


def offered(tools: Iterable[str]) -> list[str]:
    """The tools among ``tools`` that have a stub, in description order."""
    wanted = set(tools)
    return [name for name in STUBS if name in wanted]


def module_source(tools: Iterable[str], transport: Transport = "socket") -> str:
    """The text of ``indus_tools.py`` for ``tools`` (see the module notes)."""
    names = offered(tools)
    exported = ", ".join(repr(n) for n in [*names, *HELPERS, "ToolCallRefused"])
    prelude = _PRELUDE.replace("__NAMES__", exported).replace("__WAIT__", repr(RPC_CALL_WAIT_S))
    body = _SOCKET_TRANSPORT if transport == "socket" else _FILE_TRANSPORT
    return prelude + body + "".join(_function(n, STUBS[n]) for n in names)


