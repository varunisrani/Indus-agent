describe("messaging field copy", () => {
  it("labels every key the gateway catalogue sends", () => {
    const unlabelled = CATALOGUE_KEYS.filter((key) => fieldCopy(key).label === null);
    expect(unlabelled).toEqual([]);
    for (const key of CATALOGUE_KEYS) {
      const copy = fieldCopy(key);
      expect(copy.label === null ? undefined : en[copy.label]).toBeTruthy();
      if (copy.help !== null) expect(en[copy.help]).toBeTruthy();
    }
  });

  it("names the bot-sender policy in words", () => {
    const copy = fieldCopy("INDUS_TELEGRAM_ALLOW_BOTS");
    expect(copy.label).toBe("manage.messaging.field.allowBots");
    expect(copy.help).toBe("manage.messaging.help.allowBots");
    expect(copy.list).toBe(false);
    expect(fieldCopy("INDUS_SIGNAL_GROUP_ALLOWED_CHATS")).toEqual({
      label: "manage.messaging.field.allowedGroups",
      help: "manage.messaging.help.allowedGroups",
      list: true,
    });
    // the longer ending wins
    expect(fieldCopy("WHATSAPP_CLOUD_PHONE_NUMBER_ID").label).toBe(
      "manage.messaging.field.phoneNumberId",
    );
    expect(fieldCopy("TWILIO_PHONE_NUMBER").label).toBe("manage.messaging.field.phoneNumber");
  });

  it("a key with no copy reads as words, without INDUS_ or the platform prefix", () => {
    expect(fieldCopy("INDUS_SIGNAL_GROUP_MODE").label).toBeNull();
    expect(fallbackLabel("INDUS_SIGNAL_GROUP_MODE", "signal")).toBe("Group mode");
    expect(fallbackLabel("WECOM_CALLBACK_REGION", "wecom_callback")).toBe("Region");
    expect(fallbackLabel("SOME_SETTING")).toBe("Some setting");
    expect(fallbackLabel("SIGNAL_", "signal")).toBe("Signal");
  });
});
