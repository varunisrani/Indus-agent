"""Build the installer scripts from their fragments (P23-03).

    python scripts/install/build.py           # write scripts/install.sh and scripts/install.ps1
    python scripts/install/build.py --check   # fail when a built script is stale

``scripts/install.sh`` = a header, the fragments ``scripts/install/sh/*.sh`` in name order, the
generated pins section (``pins.py`` from ``pins.json``), the generated stage table (from
``stages.json``) and an entry trailer that runs ``ins_main`` only when the file is executed — so
sourcing it defines functions and runs nothing.

``scripts/install.ps1`` (P23-06) = a header, then ``scripts/install/ps/00-core.ps1`` with its one
``# @@INDUS_EMBED@@`` line replaced by two single-quoted here-strings (``$script:IndusStagesJson``
= compact ``stages.json``, ``$script:IndusPinsJson`` = compact ``pins.json``), then the other
``ps/*.ps1`` fragments in name order. Both scripts read the same two JSON files. Never edit a built
script by hand; CI runs ``--check``. ``TARGETS`` maps each built script to its builder.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import re
import sys
from collections.abc import Callable, Sequence
from pathlib import Path
from types import ModuleType
from typing import Any

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
STAGES = HERE / "stages.json"
PINS = HERE / "pins.json"
SH_DIR = HERE / "sh"
PS_DIR = HERE / "ps"
INSTALL_CMD = ROOT / "scripts" / "install.cmd"
PS_EMBED = "# @@INDUS_EMBED@@"
PS_HEADER = (
    "# Generated by scripts/install/build.py from scripts/install/ps/*.ps1, stages.json and\n"
    "# pins.json. Do not edit; change the fragments and rebuild.\n"
)

STAGE_NAME = re.compile(r"^[a-z][a-z0-9_-]{0,63}$")
EXTRA = re.compile(r"^[a-z][a-z0-9-]{0,63}$")
# Titles and categories go into single-quoted shell strings and JSON: plain text only.
PLAIN = re.compile(r"^[A-Za-z0-9 ,.()+/-]{1,80}$")

STAGES_BEGIN = (
    "# >>> generated: stages (scripts/install/build.py from stages.json; do not edit) >>>"
)
STAGES_END = "# <<< generated: stages <<<"
ENTRY = """\
# >>> generated: entry (scripts/install/build.py) >>>
# Runs only when executed (`bash install.sh`, `curl ... | bash`, where BASH_SOURCE is empty);
# sourcing this file defines its functions and runs nothing.
if [ "${BASH_SOURCE[0]:-$0}" = "$0" ]; then
    ins_main "$@"
fi
# <<< generated: entry <<<
"""


def _pins() -> ModuleType:
    spec = importlib.util.spec_from_file_location("indus_install_pins", HERE / "pins.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def load_stages(path: Path = STAGES) -> dict[str, Any]:
    data = json.loads(path.read_text(encoding="utf-8"))
    problems: list[str] = []
    if data.get("protocol_version") != 1:
        problems.append("protocol_version must be 1")
    stages = data.get("stages")
    if not isinstance(stages, list) or not stages:
        problems.append("stages must be a non-empty list")
        stages = []
    seen: set[str] = set()
    for stage in stages:
        name = stage.get("name")
        if not isinstance(name, str) or not STAGE_NAME.match(name) or name in seen:
            problems.append(f"bad or repeated stage name {name!r}")
            continue
        seen.add(name)
        for key in ("title", "category"):
            if not isinstance(stage.get(key), str) or not PLAIN.match(stage[key]):
                problems.append(f"{name}.{key} must be plain text")
        extra = stage.get("title_with_desktop")
        if extra is not None and (not isinstance(extra, str) or not PLAIN.match(extra)):
            problems.append(f"{name}.title_with_desktop must be plain text")
        if not isinstance(stage.get("needs_user_input"), bool):
            problems.append(f"{name}.needs_user_input must be true or false")
    extras = data.get("extras")
    if not isinstance(extras, dict):
        problems.append("extras must be an object")
    else:
        for key in ("always", "unless_skip_browser", "unless_skip_computer_use"):
            words = extras.get(key)
            if not isinstance(words, list) or not all(
                isinstance(w, str) and EXTRA.match(w) for w in words
            ):
                problems.append(f"extras.{key} must be a list of extra names")
    if problems:
        raise ValueError(f"{path.name}: " + "; ".join(problems))
    return data


def manifest(data: dict[str, Any], *, desktop: bool) -> dict[str, Any]:
    """The `--manifest` document (P20-09 contract): protocol 1 and one record per stage."""
    stages = []
    for stage in data["stages"]:
        title = stage["title"]
        if desktop and stage.get("title_with_desktop"):
            title = stage["title_with_desktop"]
        stages.append(
            {
                "name": stage["name"],
                "title": title,
                "category": stage["category"],
                "needs_user_input": stage["needs_user_input"],
            }
        )
    return {"protocol_version": 1, "stages": stages}


def _compact(value: Any) -> str:
    return json.dumps(value, separators=(",", ":"))


def render_stages_sh(data: dict[str, Any]) -> str:
    names = [stage["name"] for stage in data["stages"]]
    needs = [stage["name"] for stage in data["stages"] if stage["needs_user_input"]]
    lines = [
        STAGES_BEGIN,
        f"INS_STAGES='{' '.join(names)}'",
        f"INS_INPUT_STAGES='{' '.join(needs)}'",
        f"INS_MANIFEST='{_compact(manifest(data, desktop=False))}'",
        f"INS_MANIFEST_DESKTOP='{_compact(manifest(data, desktop=True))}'",
        f"INS_EXTRAS_COMMON='{' '.join(data['extras']['always'])}'",
        f"INS_EXTRAS_BROWSER='{' '.join(data['extras']['unless_skip_browser'])}'",
        f"INS_EXTRAS_COMPUTER_USE='{' '.join(data['extras']['unless_skip_computer_use'])}'",
        "ins_stage_title() {",
        '    case "$1" in',
    ]
    for stage in data["stages"]:
        lines.append(f"        {stage['name']}) printf '%s' '{stage['title']}' ;;")
    lines += ["        *) printf '%s' \"$1\" ;;", "    esac", "}", STAGES_END]
    return "\n".join(lines) + "\n"


def build_sh() -> str:
    pins = _pins()
    parts = [
        "#!/usr/bin/env bash\n",
        "# Indus Agent installer for Linux and macOS.\n",
        "# GENERATED by scripts/install/build.py from scripts/install/sh/*.sh, pins.json and\n",
        "# stages.json: edit those, never this file (CI checks it is fresh).\n",
        "\n",
    ]
    fragments = sorted(SH_DIR.glob("*.sh"))
    for index, fragment in enumerate(fragments):
        text = fragment.read_text(encoding="utf-8")
        text = "\n".join(
            line for line in text.splitlines() if line != "# shellcheck shell=bash"
        ).strip("\n")
        parts.append(text + "\n\n")
        if index == 0:
            parts.append(pins.render_sh(pins.load()) + "\n")
            parts.append(render_stages_sh(load_stages()) + "\n")
    parts.append(ENTRY)
    return "".join(parts)


def _json_one_line(value: Any) -> str:
    return json.dumps(value, separators=(",", ":"), ensure_ascii=True)


def render_ps1(install: Path = HERE) -> str:
    """The built ``install.ps1`` text from the sources under ``install`` (see the module notes)."""
    stages = _json_one_line(load_stages(install / "stages.json"))
    pins = _json_one_line(json.loads((install / "pins.json").read_text(encoding="utf-8")))
    for text in (stages, pins):
        if "'@" in text:
            raise ValueError("embedded JSON must not hold a here-string terminator ('@)")
    embed = f"$script:IndusStagesJson = @'\n{stages}\n'@\n$script:IndusPinsJson = @'\n{pins}\n'@"
    fragments = sorted((install / "ps").glob("*.ps1"))
    if not fragments or fragments[0].name != "00-core.ps1":
        raise ValueError("ps/00-core.ps1 must be the first fragment (it holds the param block)")
    parts: list[str] = []
    for index, fragment in enumerate(fragments):
        text = fragment.read_text(encoding="utf-8")
        if index == 0:
            if text.count(PS_EMBED) != 1:
                raise ValueError(f"{fragment.name} must hold exactly one {PS_EMBED} line")
            text = text.replace(PS_EMBED, embed)
        parts.append(text.rstrip("\n") + "\n")
    return PS_HEADER + "".join(parts)


def build_ps1() -> str:
    return render_ps1()


def release_repository(pins_path: Path = PINS) -> str:
    """``owner/name`` the installers download releases from (``pins.json`` ``release``)."""
    data = json.loads(pins_path.read_text(encoding="utf-8"))
    return str(data["release"]["repository"])


def latest_asset_url(repository: str, name: str) -> str:
    """A release asset of the newest release (what ``install.cmd`` downloads)."""
    return f"https://github.com/{repository}/releases/latest/download/{name}"


TARGETS: dict[str, Callable[[], str]] = {
    "scripts/install.sh": build_sh,
    "scripts/install.ps1": build_ps1,
}
EXECUTABLE = frozenset({"scripts/install.sh"})


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="build.py", description=(__doc__ or "").split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail when a built script is stale")
    args = parser.parse_args(argv)
    stale: list[str] = []
    for rel, builder in TARGETS.items():
        path = ROOT / rel
        text = builder()
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if args.check:
            if current != text:
                stale.append(rel)
            continue
        if current != text:
            path.write_text(text, encoding="utf-8", newline="\n")
            if rel in EXECUTABLE:
                path.chmod(0o755)
            print(f"build: wrote {rel}")
    for rel in stale:
        print(
            f"build: {rel} is stale -> run `python scripts/install/build.py` "
            "(edit the fragments, never the built script)",
            file=sys.stderr,
        )
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
