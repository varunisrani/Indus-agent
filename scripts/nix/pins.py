"""Render ``nix/pins.json``: the toolchain names the Nix files take from the repository (P23-13).

The flake must build with the same interpreter, Node.js and pnpm major the rest of the repository
pins, and the modules stamp the same config version the config loader expects. Those values live
in repository files; this script copies them into one JSON file the Nix code imports
(``lib.importJSON``), so Nix never parses TOML, YAML or Python to find them.

Derived values (rewritten on every run):

- ``python``: the nixpkgs interpreter attribute for ``.python-version`` (``3.13`` → ``python313``);
- ``nodejs``: ``nodejs_<major>`` from the lower bound of ``package.json`` ``engines.node``;
- ``pnpm``: ``pnpm_<major>`` from ``package.json`` ``packageManager``;
- ``configVersion``: ``CURRENT_VERSION`` in ``src/indus/foundation/config/schema.py``;
- ``image``: the product image on GHCR, ``ghcr.io/`` + ``RELEASE_REPOSITORY`` in
  ``src/indus/foundation/versions.py`` (the one release base, D-16.690); the NixOS module's
  ``container.image`` defaults to its ``stable`` tag.

Kept by hand (carried over unchanged): ``pnpmDepsHash``, the fixed-output hash of the pnpm store
for ``apps/tui`` and ``apps/web``. It needs network to compute, so the Nix lane fills it in
(``--pnpm-hash sha256-…``); ``null`` makes the build use a fake hash and print the real one.

``python scripts/nix/pins.py`` rewrites the file; ``--check`` exits 1 when it is stale.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
PINS_PATH = Path("nix") / "pins.json"
HAND_KEPT = ("pnpmDepsHash",)
COMMENT = (
    "Generated by scripts/nix/pins.py from the repository (do not edit by hand); only "
    "pnpmDepsHash is kept by hand and filled in by the Nix lane."
)

_PYTHON_VERSION = re.compile(r"^(\d+)\.(\d+)(?:\.\d+)?$")
_NODE_RANGE = re.compile(r">=\s*(\d+)(?:\.\d+){0,2}")
_PACKAGE_MANAGER = re.compile(r"^pnpm@(\d+)\.\d+\.\d+(?:[+-].*)?$")
_CONFIG_VERSION = re.compile(r"^CURRENT_VERSION\s*=\s*(\d+)\s*$", re.MULTILINE)
_RELEASE_REPOSITORY = re.compile(
    r'^RELEASE_REPOSITORY\s*=\s*"([a-z0-9][a-z0-9-]*/[a-z0-9][a-z0-9._-]*)"\s*$', re.MULTILINE
)
_SRI_SHA256 = re.compile(r"^sha256-[A-Za-z0-9+/]{43}=$")


class PinsError(Exception):
    """A repository file does not say what the pins need."""


def python_attr(root: Path) -> str:
    text = (root / ".python-version").read_text(encoding="utf-8").strip()
    match = _PYTHON_VERSION.match(text)
    if match is None:
        raise PinsError(f".python-version holds {text!r}, not MAJOR.MINOR")
    return f"python{match.group(1)}{match.group(2)}"


def _package_json(root: Path) -> dict[str, Any]:
    data = json.loads((root / "package.json").read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise PinsError("package.json is not a JSON object")
    return dict(data)  # pyright: ignore[reportUnknownArgumentType]


def nodejs_attr(root: Path) -> str:
    engines = _package_json(root).get("engines")
    wanted = engines.get("node") if isinstance(engines, dict) else None
    match = _NODE_RANGE.search(wanted) if isinstance(wanted, str) else None
    if match is None:
        raise PinsError("package.json engines.node has no '>=MAJOR' lower bound")
    return f"nodejs_{match.group(1)}"


def pnpm_attr(root: Path) -> str:
    manager = _package_json(root).get("packageManager")
    match = _PACKAGE_MANAGER.match(manager) if isinstance(manager, str) else None
    if match is None:
        raise PinsError("package.json packageManager is not 'pnpm@X.Y.Z'")
    return f"pnpm_{match.group(1)}"


def config_version(root: Path) -> int:
    schema = root / "src" / "indus" / "foundation" / "config" / "schema.py"
    match = _CONFIG_VERSION.search(schema.read_text(encoding="utf-8"))
    if match is None:
        raise PinsError(f"{schema.relative_to(root)} has no 'CURRENT_VERSION = N' line")
    return int(match.group(1))


def release_image(root: Path) -> str:
    versions = root / "src" / "indus" / "foundation" / "versions.py"
    match = _RELEASE_REPOSITORY.search(versions.read_text(encoding="utf-8"))
    if match is None:
        raise PinsError(
            f"{versions.relative_to(root)} has no 'RELEASE_REPOSITORY = \"owner/name\"'"
        )
    return f"ghcr.io/{match.group(1)}"


def valid_hash(value: object) -> bool:
    return value is None or (isinstance(value, str) and _SRI_SHA256.match(value) is not None)


def read_current(root: Path) -> dict[str, Any] | None:
    try:
        data = json.loads((root / PINS_PATH).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return dict(data) if isinstance(data, dict) else None  # pyright: ignore[reportUnknownArgumentType]


def expected(root: Path, current: dict[str, Any] | None = None) -> dict[str, Any]:
    """The file's content: derived values now, hand-kept values carried over from ``current``."""
    kept = {key: (current or {}).get(key) for key in HAND_KEPT}
    for key, value in kept.items():
        if not valid_hash(value):
            raise PinsError(f"{PINS_PATH}: {key} must be null or an SRI sha256 hash")
    return {
        "_comment": COMMENT,
        "configVersion": config_version(root),
        "image": release_image(root),
        "nodejs": nodejs_attr(root),
        "pnpm": pnpm_attr(root),
        "python": python_attr(root),
        **kept,
    }


def render(data: dict[str, Any]) -> str:
    return json.dumps(data, indent=2, sort_keys=True) + "\n"


def main(argv: Sequence[str] | None = None, *, root: Path = ROOT) -> int:
    parser = argparse.ArgumentParser(description="Render nix/pins.json from the repository.")
    parser.add_argument("--check", action="store_true", help="exit 1 when the file is stale")
    parser.add_argument("--pnpm-hash", help="record the pnpm store hash the Nix lane printed")
    args = parser.parse_args(argv)
    current = read_current(root)
    try:
        if args.pnpm_hash is not None:
            if not valid_hash(args.pnpm_hash):
                raise PinsError("--pnpm-hash must look like sha256-<44 base64 characters>")
            current = {**(current or {}), "pnpmDepsHash": args.pnpm_hash}
        want = render(expected(root, current))
    except (OSError, ValueError, PinsError) as exc:
        print(f"nix pins: {exc}", file=sys.stderr)
        return 2
    path = root / PINS_PATH
    have = path.read_text(encoding="utf-8") if path.is_file() else None
    if args.check:
        if have != want:
            print(f"{PINS_PATH} is stale; run: uv run python scripts/nix/pins.py", file=sys.stderr)
            return 1
        return 0
    if have != want:
        tmp = path.with_name(path.name + ".tmp")
        tmp.write_text(want, encoding="utf-8")
        tmp.replace(path)
        print(f"wrote {PINS_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
