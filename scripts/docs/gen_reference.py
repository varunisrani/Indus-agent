def starter_skills(skills_dir: Path = SKILLS_DIR) -> list[tuple[str, str, str]]:
    """``(name, category, description)`` of each ``SKILL.md`` under ``skills_dir``, sorted."""
    from indus.learning.skills.format import parse_skill

    out: list[tuple[str, str, str]] = []
    for path in sorted(skills_dir.rglob("SKILL.md")):
        parsed = parse_skill(path.read_text(encoding="utf-8"))
        meta = parsed.frontmatter
        category = meta.indus.category or path.parent.parent.name
        out.append((meta.name, category, meta.description))
    return sorted(out, key=lambda row: (row[1], row[0]))


