def _field_rows(model: type[Any]) -> list[tuple[str, ...]]:
    rows: list[tuple[str, ...]] = []
    for name, info in model.model_fields.items():
        rows.append(
            (
                code(info.alias or name),
                cell(type_text(info.annotation)),
                "yes" if info.is_required() else "no",
                cell(info.description or ""),
            )
        )
    return rows


def _fields_block(title: str, model: type[Any]) -> list[str]:
    rows = _field_rows(model)
    if not rows:
        return [f"{title}: none.", ""]
    return [f"{title}:", ""] + table(("Field", "Type", "Required", "Meaning"), rows) + [""]


def render_protocol() -> str:
    from indus.protocol import errors, events, methods, server_requests

    body: list[str] = [
        "The JSON-RPC protocol between the agent host and its surfaces (TUI, desktop, "
        "dashboard, editors attached through the daemon). "
        f"Protocol version: {methods.PROTOCOL_VERSION}.",
        "",
        "## Methods",
        "",
    ]
    body += table(
        ("Method", "What it does"),
        [(f"[`{n}`](#{slug(n)})", cell(spec.summary)) for n, spec in methods.METHODS.items()],
    ) + [""]
    for name, spec in methods.METHODS.items():
        body += [f"### {name}", "", spec.summary, ""]
        body += _fields_block("Parameters", spec.params)
        body += _fields_block("Result", spec.result)
        body += ["Errors: " + ", ".join(code(e.name) for e in spec.errors) + ".", ""]
    body += ["## Notifications", ""]
    body += table(
        ("Method", "What it carries"),
        [(code(n), cell(first_line(m.__doc__))) for n, m in methods.NOTIFICATIONS.items()],
    ) + [""]
    body += ["## Events", ""]
    body += table(
        ("Event", "What it means"),
        [(f"[`{n}`](#{slug(n)})", cell(first_line(m.__doc__))) for n, m in events.EVENTS.items()],
    ) + [""]
    for name, model in events.EVENTS.items():
        body += [f"### {name}", "", first_paragraph(model.__doc__), ""]
        body += _fields_block("Fields", model)
    body += ["## Server requests", ""]
    body += [
        f"The host asks the person something through `{server_requests.SERVER_REQUEST_METHOD}`; "
        "the surface answers with `server_request.answer`.",
        "",
    ]
    for kind, (request, answer) in server_requests.SERVER_REQUEST_KINDS.items():
        body += [f"### {kind}", "", first_paragraph(request.__doc__), ""]
        body += _fields_block("Request", request)
        body += _fields_block("Answer", answer)
    body += ["## Error codes", ""]
    body += [
        "Each code has one meaning across every method (D-16.27). The group decides the HTTP "
        "status a code maps to over HTTP.",
        "",
    ]
    body += table(
        ("Code", "Name", "Group", "HTTP", "Meaning"),
        [
            (
                str(e.code),
                code(e.name),
                code(str(e.group)),
                str(errors.GROUP_STATUS.get(e.group, "")),
                cell(e.meaning),
            )
            for e in errors.ERROR_TABLE
        ],
    ) + [""]
    if errors.OUT_OF_BAND_ERRORS:
        body += ["Codes that never answer a method call, and where they travel:", ""]
        body += table(
            ("Name", "Where"),
            [(code(e.name), cell(where)) for e, where in errors.OUT_OF_BAND_ERRORS.items()],
        ) + [""]
    return page("Protocol", "Methods, events and error codes of the agent protocol.", body)


