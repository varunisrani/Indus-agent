def mcp_serve_tools() -> list[Any]:
    """The tools of a server built by the same registration functions ``indus mcp serve`` uses
    (the parts behind the tools are never called, so stand-ins are enough)."""
    from mcp.server import MCPServer

    from indus.mcp_serve import server as serve_module

    built = MCPServer(serve_module.SERVER_NAME, instructions=serve_module.INSTRUCTIONS)
    register = cast(Callable[..., None], serve_module._register)  # pyright: ignore[reportPrivateUsage]
    register_approvals = cast(
        Callable[..., None],
        serve_module._register_approvals,  # pyright: ignore[reportPrivateUsage]
    )
    register(built, None, None, None)
    register_approvals(built, None)
    return list(asyncio.run(built.list_tools()))


def render_mcp_serve() -> str:
    from indus.mcp_serve import server as serve_module

    tools = mcp_serve_tools()
    body: list[str] = [
        "`indus mcp serve` runs an MCP server on stdio that gives another agent or editor the "
        "chats this profile's gateway is connected to. Every tool answers one JSON text; a "
        "problem is a JSON object with an `error` field.",
        "",
    ]
    body += table(
        ("Tool", "What it does"),
        [(f"[`{t.name}`](#{slug(t.name)})", cell(first_paragraph(t.description))) for t in tools],
    ) + [""]
    for tool in tools:
        body += [f"## {tool.name}", ""]
        if tool.name in serve_module.APPROVAL_TOOLS:
            body += ["Offered only when the running daemon has an approval queue.", ""]
        text = inspect.cleandoc(tool.description or "")
        body += [text.split("\nArgs:", 1)[0].strip(), ""]
        rows = _parameter_rows(cast(Mapping[str, Any], tool.input_schema))
        if rows:
            body += table(("Argument", "Type", "Required", "Default", "Meaning"), rows) + [""]
    return page("MCP server tools", "The tools `indus mcp serve` offers.", body)


