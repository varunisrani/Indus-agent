def _modules_cell(modules: Iterable[str], limit: int = 3) -> str:
    ordered = sorted(modules)
    shown = ", ".join(code(m) for m in ordered[:limit])
    extra = len(ordered) - limit
    return shown + (f" and {extra} more" if extra > 0 else "")


def platform_env(entries: Iterable[Any]) -> dict[str, list[tuple[str, str]]]:
    """``env name -> [(platform label, role)]`` from the gateway's platform registry."""
    out: dict[str, list[tuple[str, str]]] = {}
    for entry in entries:
        for attr, role in PLATFORM_ROLES:
            value = getattr(entry, attr, None)
            names = (value,) if isinstance(value, str) else tuple(value or ())
            for name in names:
                if name:
                    out.setdefault(name, []).append((entry.label, role))
    return out


def render_env(scan: EnvScan | None = None) -> str:
    from indus.gateway.registry import builtin_entries
    from indus.providers import bundled

    found = scan or scan_env()
    platforms = platform_env(builtin_entries())
    provider_names: dict[str, list[str]] = {}
    for profile in bundled.PROFILES:
        for name in (*profile.env_vars, profile.base_url_env_var):
            if name:
                provider_names.setdefault(name, []).append(profile.display_name or profile.name)
    tool_secrets: dict[str, list[str]] = {}
    for tool_name, entry in sorted(scan_tools().entries.items()):
        for secret in entry.requires_secrets:
            tool_secrets.setdefault(secret, []).append(tool_name)

    body: list[str] = [
        "Variables can be set in the shell or in the profile's `.env` file (the shell wins). "
        "Keys and tokens are better kept in the keychain (`indus auth`); a variable of the "
        "same name still works.",
        "",
        "## Indus Agent variables",
        "",
    ]
    indus_rows = [
        (code(name), cell(ENV_NOTES.get(name, "")), _modules_cell(mods))
        for name, mods in sorted(found.indus.items())
        if name not in platforms
    ]
    indus_rows += [
        (code(prefix + "*"), "a family of names sharing this prefix", _modules_cell(mods))
        for prefix, mods in sorted(found.prefixes.items())
    ]
    body += table(("Variable", "Notes", "Used in"), indus_rows) + [""]
    body += ["## Model provider keys", ""]
    body += table(
        ("Variable", "Providers"),
        [(code(n), cell(", ".join(p))) for n, p in sorted(provider_names.items())],
    ) + [""]
    body += ["## Messaging platforms", ""]
    body += table(
        ("Variable", "Platform", "Holds"),
        [
            (code(n), cell(", ".join(sorted({p for p, _ in uses}))), cell(uses[0][1]))
            for n, uses in sorted(platforms.items())
        ],
    ) + [""]
    if tool_secrets:
        body += ["## Tool services", ""]
        body += table(
            ("Variable", "Tools"),
            [
                (code(n), ", ".join(code(t) for t in tools))
                for n, tools in sorted(tool_secrets.items())
            ],
        ) + [""]
    others = {
        n: m
        for n, m in found.other.items()
        if n not in provider_names and n not in platforms and n not in tool_secrets
    }
    if others:
        body += ["## Other variables read", ""]
        body += [
            "Standard and vendor variables the program also reads (proxies, editors, cloud "
            "SDK settings and the like).",
            "",
        ]
        body += table(
            ("Variable", "Used in"),
            [(code(n), _modules_cell(m)) for n, m in sorted(others.items())],
        ) + [""]
    return page(
        "Environment variables",
        "Every environment variable Indus Agent reads, found in its source code.",
        body,
    )


