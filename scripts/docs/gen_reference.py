def _model_member(annotation: object) -> type[Any] | None:
    from pydantic import BaseModel

    members = typing.get_args(annotation) or (annotation,)
    for member in members:
        if isinstance(member, type) and issubclass(member, BaseModel):
            return member
    return None


def config_rows(
    model: type[Any], prefix: str, defaults: Mapping[str, Any]
) -> list[tuple[str, ...]]:
    """``(dotted key, type, default, description)`` for every leaf under ``model``."""
    rows: list[tuple[str, ...]] = []
    for name, info in model.model_fields.items():
        key = info.alias or name
        if key.startswith("_"):
            continue
        path = f"{prefix}{key}"
        value = defaults.get(key) if isinstance(defaults, Mapping) else None
        sub = _model_member(info.annotation)
        description = info.description or ""
        if sub is not None and sub is not info.annotation:
            # a shorthand slot (``model: <id>``) that also takes the section's keys
            rows.append((path, type_text(info.annotation), "", description))
        if sub is not None:
            inner = value if isinstance(value, Mapping) else {}
            rows.extend(config_rows(sub, path + ".", cast(Mapping[str, Any], inner)))
            continue
        rows.append((path, type_text(info.annotation), show_value(value), description))
    return rows


def render_config() -> str:
    from indus.foundation.config import schema

    defaults = schema.DEFAULTS
    body: list[str] = [
        "Settings live in `config.yaml` in the profile home. `indus config show` prints the "
        "file, `indus config set <key> <value>` changes one key. Keys are written here as "
        "dotted paths: `agent.max_turns` is `max_turns` inside the `agent:` section.",
        "",
    ]
    model = schema.ConfigModel
    for name, info in model.model_fields.items():
        key = info.alias or name
        if key == schema.VERSION_KEY:
            continue
        body += [f"## {key}", ""]
        if info.description:
            body += [info.description[0].upper() + info.description[1:] + ".", ""]
        sub = _model_member(info.annotation)
        value = defaults.get(key)
        if sub is None:
            rows = [(key, type_text(info.annotation), show_value(value), info.description or "")]
        else:
            rows = config_rows(sub, key + ".", cast(Mapping[str, Any], value or {}))
            if sub is not info.annotation:
                rows.insert(0, (key, type_text(info.annotation), "", info.description or ""))
        body += table(
            ("Key", "Type", "Default", "Meaning"),
            [(code(k), cell(t), code(d) if d else "", cell(m)) for k, t, d, m in rows],
        )
        body.append("")
    return page(
        "Configuration keys",
        "Every key of `config.yaml` with its type and built-in value. A key you leave out keeps "
        "following the built-in value, also when a later release changes it.",
        body,
    )


# -- source scans -------------------------------------------------------------------------------

INDUS_NAME = re.compile(r"^INDUS_[A-Z0-9_]*[A-Z0-9]$")
INDUS_PREFIX = re.compile(r"^INDUS_[A-Z0-9_]*_$")
ENV_NAME = re.compile(r"^[A-Z][A-Z0-9_]*$")
ENV_RECEIVERS = ("environ", "env", "getenv")


def source_modules(package_dir: Path = PACKAGE_DIR) -> Iterator[tuple[str, ast.Module]]:
    """``(dotted module name, parsed tree)`` for every module under the package, sorted."""
    base = package_dir.parent
    for path in sorted(package_dir.rglob("*.py")):
        parts = path.relative_to(base).with_suffix("").parts
        name = ".".join(parts[:-1] if parts[-1] == "__init__" else parts)
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"))
        except (SyntaxError, UnicodeDecodeError):
            continue
        yield name, tree


def _receiver_reads_env(node: ast.expr) -> bool:
    text = ast.unparse(node).lower()
    return any(word in text for word in ENV_RECEIVERS)


@dataclass
class EnvScan:
    indus: dict[str, set[str]] = field(default_factory=dict[str, set[str]])
    prefixes: dict[str, set[str]] = field(default_factory=dict[str, set[str]])
    other: dict[str, set[str]] = field(default_factory=dict[str, set[str]])


def scan_env(package_dir: Path = PACKAGE_DIR) -> EnvScan:
    """Names the source mentions: every ``INDUS_*`` string, and other upper-case names read
    through an env mapping (``os.environ.get("X")``, ``env["X"]``, ``getenv("X")``)."""
    found = EnvScan()
    for module, tree in source_modules(package_dir):
        for node in ast.walk(tree):
            if isinstance(node, ast.Constant) and isinstance(node.value, str):
                if INDUS_NAME.match(node.value):
                    found.indus.setdefault(node.value, set()).add(module)
                elif INDUS_PREFIX.match(node.value):
                    found.prefixes.setdefault(node.value, set()).add(module)
            name: str | None = None
            if isinstance(node, ast.Call) and node.args:
                arg = node.args[0]
                func = node.func
                if isinstance(arg, ast.Constant) and isinstance(arg.value, str):
                    if isinstance(func, ast.Attribute) and func.attr in ("get", "pop", "getenv"):
                        if func.attr == "getenv" or _receiver_reads_env(func.value):
                            name = arg.value
                    elif isinstance(func, ast.Name) and func.id == "getenv":
                        name = arg.value
            elif isinstance(node, ast.Subscript) and _receiver_reads_env(node.value):
                key = node.slice
                if isinstance(key, ast.Constant) and isinstance(key.value, str):
                    name = key.value
            if name and ENV_NAME.match(name) and not name.startswith("INDUS_"):
                found.other.setdefault(name, set()).add(module)
    return found


# -- tools --------------------------------------------------------------------------------------


def tool_modules(package_dir: Path = PACKAGE_DIR) -> list[str]:
    """Modules with a top-level ``register_tools(registry)`` (one required positional)."""
    out: list[str] = []
    for module, tree in source_modules(package_dir):
        for node in tree.body:
            if isinstance(node, ast.FunctionDef) and node.name == "register_tools":
                required = len(node.args.args) - len(node.args.defaults)
                keywords_optional = all(d is not None for d in node.args.kw_defaults)
                if required == 1 and keywords_optional:
                    out.append(module)
    return out


@dataclass
class ToolScan:
    entries: dict[str, Any]
    modules: dict[str, str]
    failed: dict[str, str]


def scan_tools(modules: Sequence[str] | None = None) -> ToolScan:
    """Register each module into its own registry; the first module to register a name wins."""
    from indus.tools.registry import ToolRegistry

    entries: dict[str, Any] = {}
    owner: dict[str, str] = {}
    failed: dict[str, str] = {}
    for module in tool_modules() if modules is None else modules:
        registry = ToolRegistry()
        try:
            importlib.import_module(module).register_tools(registry)
        except Exception as exc:  # an optional extra missing: recorded, not fatal
            failed[module] = type(exc).__name__
            continue
        for entry in registry.entries():
            if entry.name not in entries:
                entries[entry.name] = entry
                owner[entry.name] = module
    return ToolScan(entries, owner, failed)


def _schema_type(schema: Mapping[str, Any]) -> str:
    if "enum" in schema:
        return " | ".join(repr(v) if isinstance(v, str) else str(v) for v in schema["enum"])
    kind = schema.get("type")
    if isinstance(kind, list):
        return " or ".join(str(k) for k in cast(list[object], kind))
    if kind == "array":
        items = schema.get("items")
        inner = _schema_type(cast(Mapping[str, Any], items)) if isinstance(items, Mapping) else ""
        return f"array of {inner}" if inner else "array"
    if kind:
        return str(kind)
    for key in ("anyOf", "oneOf"):
        options = schema.get(key)
        if isinstance(options, list):
            return " or ".join(
                _schema_type(cast(Mapping[str, Any], o))
                for o in cast(list[object], options)
                if isinstance(o, Mapping)
            )
    return "any"


def _parameter_rows(parameters: Mapping[str, Any] | None) -> list[tuple[str, ...]]:
    if not parameters:
        return []
    props = cast(Mapping[str, Any], parameters.get("properties") or {})
    required = set(cast(list[str], parameters.get("required") or []))
    rows: list[tuple[str, ...]] = []
    for name, raw in props.items():
        spec = cast(Mapping[str, Any], raw) if isinstance(raw, Mapping) else {}
        default = show_value(spec["default"]) if "default" in spec else ""
        rows.append(
            (
                code(name),
                cell(_schema_type(spec)),
                "yes" if name in required else "no",
                code(default) if default else "",
                cell(first_paragraph(str(spec.get("description", "")))),
            )
        )
    return rows


GROUP_AT = 4
"""Tools sharing a ``prefix_`` are shown as one ``prefix_*`` entry from this many on."""


def tool_list(names: Sequence[str]) -> str:
    """Tool names for a table cell; a family of ``GROUP_AT`` or more names that share a prefix
    (``browser_*``) is shown once with its size, in the place of its first member."""
    families: dict[str, list[str]] = {}
    for name in names:
        head, sep, _ = name.partition("_")
        if sep:
            families.setdefault(head, []).append(name)
    shown: list[str] = []
    done: set[str] = set()
    for name in names:
        head, sep, _ = name.partition("_")
        members = families.get(head, []) if sep else []
        if len(members) >= GROUP_AT:
            if head not in done:
                done.add(head)
                shown.append(f"{code(head + '_*')} ({len(members)} tools)")
            continue
        shown.append(code(name))
    return ", ".join(shown)


def render_tools(scan: ToolScan | None = None) -> str:
    from indus.tools import toolsets

    found = scan or scan_tools()
    names = sorted(found.entries, key=lambda n: (found.entries[n].toolset, n))
    body: list[str] = [
        "Tools are what the model can call. A session gets the tools of its toolsets "
        "(`indus tools` chooses them per platform); a tool whose service, key or library is "
        "missing is left out of the session automatically.",
        "",
        "## All tools",
        "",
    ]
    body += table(
        ("Tool", "Toolset", "What it does"),
        [
            (
                f"[`{n}`](#{slug(n)})",
                code(found.entries[n].toolset),
                cell(first_paragraph(found.entries[n].schema.get("description"))),
            )
            for n in names
        ],
    )
    body.append("")
    for name in names:
        entry = found.entries[name]
        body += [f"### {name}", ""]
        body += [inspect.cleandoc(str(entry.schema.get("description") or "")).strip(), ""]
        facts = [f"Toolset: `{entry.toolset}`."]
        if entry.requires_secrets:
            facts.append("Needs: " + ", ".join(code(s) for s in entry.requires_secrets) + ".")
        body += [" ".join(facts), ""]
        rows = _parameter_rows(entry.parameters)
        if rows:
            body += table(("Parameter", "Type", "Required", "Default", "Meaning"), rows) + [""]
    body += ["## Toolsets", ""]
    body += [
        "A toolset names a group of tools and may include other toolsets. Platform bundles "
        "(`indus-<platform>`) are what each surface starts from.",
        "",
    ]
    rows = []
    for name, toolset in sorted(toolsets.TOOLSETS.items()):
        notes = []
        if toolset.platforms:
            notes.append("only on " + ", ".join(sorted(toolset.platforms)))
        if toolset.posture:
            notes.append("per session, never saved")
        if not toolset.registry_members:
            notes.append("fixed list")
        rows.append(
            (
                code(name),
                cell(toolset.description),
                tool_list(toolset.tools),
                ", ".join(code(t) for t in toolset.includes),
                cell("; ".join(notes)),
            )
        )
    body += table(("Toolset", "What it is for", "Tools", "Includes", "Notes"), rows) + [""]
    if found.failed:
        body += ["## Not listed", ""]
        body += [
            "These modules register tools but could not be loaded where this page was "
            "generated: " + ", ".join(code(m) for m in sorted(found.failed)) + ".",
            "",
        ]
    return page("Tools and toolsets", "Every tool Indus Agent ships, and the toolsets.", body)


