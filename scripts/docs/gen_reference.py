# -- Markdown helpers ---------------------------------------------------------------------------


def cell(value: object) -> str:
    """Text safe inside one Markdown table cell: one line, pipes escaped."""
    text = " ".join(str(value).split())
    return text.replace("|", "\\|")


def code(value: object) -> str:
    """Inline code for a table cell; backticks inside widen the fence."""
    text = cell(value)
    if not text:
        return ""
    fence = "``" if "`" in text else "`"
    pad = " " if fence == "``" else ""
    return f"{fence}{pad}{text}{pad}{fence}"


def table(headers: Sequence[str], rows: Iterable[Sequence[object]]) -> list[str]:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    for row in rows:
        lines.append("| " + " | ".join(str(c) for c in row) + " |")
    return lines


def first_paragraph(text: str | None) -> str:
    cleaned = inspect.cleandoc(text or "").strip()
    return cleaned.split("\n\n", 1)[0].replace("\n", " ").strip()


def first_line(text: str | None) -> str:
    cleaned = inspect.cleandoc(text or "").strip()
    return cleaned.splitlines()[0].strip() if cleaned else ""


def page(title: str, intro: str, body: Iterable[str]) -> str:
    lines = [MARKER, "", f"# {title}", "", intro, ""]
    lines.extend(body)
    while lines and not lines[-1]:
        lines.pop()
    return "\n".join(lines) + "\n"


def show_value(value: object) -> str:
    """A default as it would be written in YAML-like text, summarised when long."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return '""' if value == "" else value
    if isinstance(value, Mapping):
        mapping = cast(Mapping[str, object], value)
        if not mapping:
            return "{}"
        text = "{" + ", ".join(f"{k}: {show_value(v)}" for k, v in mapping.items()) + "}"
        return text if len(text) <= LONG_VALUE else f"(a mapping of {len(mapping)} entries)"
    if isinstance(value, list | tuple | set | frozenset):
        items = cast(Iterable[object], value)
        seq = sorted(items, key=str) if isinstance(value, set | frozenset) else list(items)
        if not seq:
            return "[]"
        text = "[" + ", ".join(show_value(v) for v in seq) + "]"
        return text if len(text) <= LONG_VALUE else f"(a list of {len(seq)} items)"
    return str(value)


def type_text(annotation: object) -> str:
    """A short readable name for a type annotation."""
    origin = typing.get_origin(annotation)
    args = typing.get_args(annotation)
    if annotation is type(None):
        return "null"
    if origin is typing.Literal:
        return " | ".join(repr(a) if isinstance(a, str) else str(a) for a in args)
    if origin in (typing.Union, types.UnionType):
        return " or ".join(type_text(a) for a in args)
    if origin is typing.Annotated:
        return type_text(args[0])
    if origin is not None:
        name = getattr(origin, "__name__", str(origin))
        inner = ", ".join(type_text(a) for a in args if a is not Ellipsis)
        return f"{name}[{inner}]" if inner else name
    if isinstance(annotation, type):
        return annotation.__name__
    text = str(annotation)
    return re.sub(r"\b(?:[a-z_][\w]*\.)+", "", text)


# -- CLI ----------------------------------------------------------------------------------------


def _help_text(cmd: Any) -> str:
    text = inspect.cleandoc(cmd.help or "")
    text = text.split("\f", 1)[0]
    lines = [line for line in text.splitlines() if line.strip() != "\b"]
    return "\n".join(lines).strip()


def _option_names(param: Any) -> str:
    names = ", ".join(param.opts)
    if getattr(param, "secondary_opts", None):
        names += " / " + ", ".join(param.secondary_opts)
    return names


def _option_value(param: Any) -> str:
    import click

    if getattr(param, "count", False):
        kind = "count"
    elif getattr(param, "is_flag", False):
        kind = "flag"
    elif isinstance(param.type, click.Choice):
        kind = " | ".join(str(c) for c in param.type.choices)
    else:
        kind = param.type.name.upper()
    if getattr(param, "multiple", False):
        kind += " (repeatable)"
    return kind


def _option_default(param: Any) -> str:
    default = param.default
    if callable(default):
        return "computed"
    if default is None or default == () or type(default).__name__ == "Sentinel":
        return ""
    if getattr(param, "is_flag", False) and not getattr(param, "count", False):
        if getattr(param, "secondary_opts", None):
            return param.opts[0] if default else param.secondary_opts[0]
        return "on" if default is True else ""
    if getattr(param, "count", False) and not default:
        return ""
    return code(show_value(default))


@dataclass
class CliCommand:
    path: str
    command: Any
    context: Any
    children: list[CliCommand] = field(default_factory=list["CliCommand"])


def walk_cli(command: Any, name: str, parent: Any = None) -> CliCommand:
    """The visible command tree under ``command``, in each group's own listing order."""
    import click

    ctx = click.Context(command, info_name=name, parent=parent)
    path = f"{parent.command_path} {name}" if parent is not None else name
    node = CliCommand(path, command, ctx)
    if isinstance(command, click.Group):
        for sub_name in command.list_commands(ctx):
            sub = command.get_command(ctx, sub_name)
            if sub is None or sub.hidden:
                continue
            node.children.append(walk_cli(sub, sub_name, ctx))
    return node


def _flatten(node: CliCommand) -> Iterator[CliCommand]:
    yield node
    for child in node.children:
        yield from _flatten(child)


def _cli_section(node: CliCommand, level: int) -> list[str]:
    import click

    cmd = node.command
    out = [f"{'#' * level} {node.path}", ""]
    if cmd.deprecated:
        out += ["*Deprecated.*", ""]
    helptext = _help_text(cmd)
    if helptext:
        out += [helptext, ""]
    pieces = cmd.collect_usage_pieces(node.context)
    out += ["```text", " ".join([node.path, *pieces]).rstrip(), "```", ""]
    arguments = [p for p in cmd.params if isinstance(p, click.Argument)]
    if arguments:
        rows = [
            (
                code(p.human_readable_name),
                "yes" if p.required else "no",
                "many" if p.nargs == -1 else str(p.nargs),
            )
            for p in arguments
        ]
        out += table(("Argument", "Required", "Count"), rows) + [""]
    options = [
        p
        for p in cmd.params
        if isinstance(p, click.Option) and not p.hidden and "--help" not in p.opts
    ]
    if options:
        rows = [
            (code(_option_names(p)), cell(_option_value(p)), _option_default(p), cell(p.help or ""))
            for p in options
        ]
        out += table(("Option", "Value", "Default", "What it does"), rows) + [""]
    if node.children:
        rows = [
            (f"[`{child.path}`](#{slug(child.path)})", cell(child.command.get_short_help_str(200)))
            for child in node.children
        ]
        out += table(("Command", "What it does"), rows) + [""]
    return out


def slug(heading: str) -> str:
    """The anchor MkDocs' table of contents gives a heading made of plain words."""
    text = re.sub(r"[^\w\s-]", "", heading.lower()).strip()
    return re.sub(r"[\s]+", "-", text)


def render_cli(root: Any = None, name: str = "indus") -> str:
    if root is None:
        from indus.cli.app import cli as root
    tree = walk_cli(root, name)
    body: list[str] = [
        "Every command also accepts `--help`, which prints the same text in the terminal.",
        "",
    ]
    body += _cli_section(tree, 2)
    for top in tree.children:
        for node in _flatten(top):
            body += _cli_section(node, 2 if node is top else 3)
    return page(
        "Command line",
        "Every `indus` command with its arguments, options and subcommands.",
        body,
    )


