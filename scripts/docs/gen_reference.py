"""Write the generated reference pages of the user docs from the code (P25-15).

Every page under ``docs/user/reference/`` whose first line is ``MARKER`` belongs to this script;
pages without it (``trajectory-format.md``) are hand-written and never touched. Each page is
rendered from what the program itself declares, so nothing here lists commands, keys or tools:

- ``cli.md``: the ``indus`` click tree (lazy commands resolved, hidden ones left out);
- ``slash-commands.md``: the slash-command registry;
- ``configuration.md``: the Pydantic config models behind the defaults table (D-16.32);
- ``environment-variables.md``: ``INDUS_*`` names and other variables the source reads (an AST
  scan of ``src/indus``), provider key names, messaging platform names and tool secrets;
- ``tools.md``: every tool a ``register_tools(registry)`` function in ``src/indus`` registers,
  and the toolsets;
- ``protocol.md``: methods, notifications, events, server requests and error codes (D-16.27);
- ``mcp-serve-tools.md``: the tools ``indus mcp serve`` offers;
- ``skills.md``: the starter skills in ``skills/``;
- ``messaging-platforms.md`` and ``providers.md``: the gateway and provider registries.

Usage: ``python scripts/docs/gen_reference.py`` writes the pages (and removes generated pages no
longer produced); ``--check`` writes nothing and exits 1 naming every stale, missing or orphaned
page; ``--out DIR`` targets another folder. Output never depends on the machine: no timestamps,
no paths outside the repository, ``INDUS_*`` variables cleared before anything is imported.
"""

