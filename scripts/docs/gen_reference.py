def is_generated(path: Path) -> bool:
    try:
        with path.open(encoding="utf-8") as handle:
            return handle.readline().rstrip("\n") == MARKER
    except OSError:
        return False


def stale_report(out_dir: Path, pages: Mapping[str, str]) -> list[str]:
    """One line per page that differs, is missing, or is generated but no longer produced."""
    problems: list[str] = []
    for name, text in pages.items():
        path = out_dir / name
        if not path.is_file():
            problems.append(f"{name}: missing")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(f"{name}: stale")
    for path in sorted(out_dir.glob("*.md")):
        if path.name not in pages and is_generated(path):
            problems.append(f"{path.name}: generated page no longer produced")
    return problems


def write_pages(out_dir: Path, pages: Mapping[str, str]) -> list[str]:
    """Write changed pages and remove orphaned generated ones; the names touched."""
    out_dir.mkdir(parents=True, exist_ok=True)
    touched: list[str] = []
    for name, text in pages.items():
        path = out_dir / name
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8", newline="\n")
            touched.append(name)
    for path in sorted(out_dir.glob("*.md")):
        if path.name not in pages and is_generated(path):
            path.unlink()
            touched.append(path.name)
    return touched


def _quiet_environment() -> None:
    """Make rendering independent of the shell it runs in."""
    for name in [n for n in os.environ if n.startswith("INDUS_")]:
        del os.environ[name]
    os.environ["NO_COLOR"] = "1"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--check", action="store_true", help="report stale pages, write nothing")
    parser.add_argument("--out", type=Path, default=OUT_DIR, help="target folder")
    args = parser.parse_args(argv)
    pages = render_all()
    if args.check:
        problems = stale_report(args.out, pages)
        for line in problems:
            print(f"{args.out.name}/{line}", file=sys.stderr)
        if problems:
            print(f"run `{COMMAND}` and commit the result", file=sys.stderr)
            return 1
        print(f"{len(pages)} generated reference pages are fresh")
        return 0
    touched = write_pages(args.out, pages)
    print(
        f"wrote {len(touched)} of {len(pages)} pages"
        + (f": {', '.join(touched)}" if touched else "")
    )
    return 0


if __name__ == "__main__":
    if str(SRC) not in sys.path:
        sys.path.insert(0, str(SRC))
    _quiet_environment()
    raise SystemExit(main())
