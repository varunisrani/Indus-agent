SURFACE_LABELS = {
    "cli": "classic CLI",
    "tui": "TUI",
    "gateway": "messaging",
    "desktop": "desktop",
}


def render_slash() -> str:
    from indus.service.commands.registry import CATEGORY_TITLES, REGISTRY, SURFACES

    body: list[str] = []
    for category, commands in REGISTRY.by_category().items():
        body += [f"## {CATEGORY_TITLES[category]}", ""]
        rows = []
        for cmd in commands:
            aliases = ", ".join(code("/" + a) for a in cmd.aliases)
            args = cmd.args_hint
            if cmd.subcommands:
                args = (args + " " if args else "") + "(" + ", ".join(cmd.subcommands) + ")"
            where = (
                "everywhere"
                if cmd.surfaces == SURFACES
                else ", ".join(SURFACE_LABELS.get(s, s) for s in sorted(cmd.surfaces))
            )
            rows.append((code("/" + cmd.name), aliases, code(args), cell(cmd.description), where))
        body += table(("Command", "Aliases", "Arguments", "What it does", "Offered in"), rows)
        body.append("")
    return page(
        "Slash commands",
        "Commands typed in a chat, starting with `/`. Names and aliases ignore case. "
        "`/help` lists the ones the current surface offers.",
        body,
    )


